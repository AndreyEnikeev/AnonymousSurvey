namespace Auth.Models
{
    /// <summary>
    /// Модель данных (DTO) для запроса на обновление пары токенов.
    /// Используется в эндпоинте POST /api/auth/refresh.
    /// 
    /// Содержит только refresh-токен: клиент приходит сюда именно тогда,
    /// когда access-токен просрочен, и передавать его бессмысленно.
    /// </summary>
    public class RefreshRequest
    {
        /// <summary>
        /// Действующий refresh-токен, полученный при входе (O-01)
        /// или при предыдущем обновлении (этот же эндпоинт).
        /// 
        /// Сервер проверит:
        ///  1) токен существует в Redis и не истёк;
        ///  2) связанный пользователь ещё существует в БД.
        /// При успехе старый токен будет отозван (rotation),
        /// и клиент получит новую пару access + refresh.
        /// </summary>
        public string RefreshToken { get; init; } = string.Empty;
    }
}